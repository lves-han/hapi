import type { Database } from 'bun:sqlite'

export const businessTables = [
    'sessions', 'machines', 'messages', 'message_epochs', 'users', 'push_subscriptions',
    'fcm_devices', 'session_scratchlist', 'usage_events', 'usage_scan_state', 'events', 'event_links'
] as const
export const postgresSchemaVersion = 26

export function postgresSchema(db: Database): { tables: string[]; indexes: string[] } {
    const tables = businessTables.map(name => {
        const row = db.query("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?").get(name) as { sql: string }
        let sql = row.sql.replace(/\bINTEGER\b/g, 'BIGINT').replace(/\bREAL\b/g, 'DOUBLE PRECISION')
            .replace(/BIGINT PRIMARY KEY AUTOINCREMENT/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        if (name === 'messages') {
            sql = sql.replace('content TEXT NOT NULL', `content BYTEA NOT NULL,
                content_encoding TEXT GENERATED ALWAYS AS (
                    CASE WHEN substring(content FROM 1 FOR 4) = decode('28b52ffd', 'hex') THEN 'zstd' ELSE 'json' END
                ) STORED`)
        }
        if (name === 'messages' || name === 'events') {
            sql = sql.replace(/\(\s*/, '(insertion_order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,\n')
        }
        return sql
    })
    const indexes = (db.query("SELECT sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL ORDER BY name").all() as { sql: string }[])
        .map(row => row.sql)
    return { tables, indexes }
}
