#!/bin/sh
set -eu
: "${HAPI_DATABASE_PASSWORD:?Set HAPI_DATABASE_PASSWORD}"
psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v app_password="$HAPI_DATABASE_PASSWORD" <<'SQL'
CREATE ROLE hapi LOGIN PASSWORD :'app_password';
ALTER DATABASE hapi OWNER TO hapi;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO hapi;
SQL
